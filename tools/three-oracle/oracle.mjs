// Runs samples/three/tests/fixtures/cases.json on three.js 0.187.0 in pinned
// Chromium and writes samples/three/tests/fixtures/three-0.187.0.json, which
// samples/three/tests/oracle.rs compares the port with.
//
//     python -I tools/three-oracle/make_cases.py
//     npm ci --prefix tools/three-oracle
//     node tools/three-oracle/oracle.mjs CHROME
//
// CHROME is the `chrome` binary of Chrome for Testing 147.0.7727.50, the
// build Div's census pins. The oracle runs in Chromium, not Node, because
// their Math differs: Node's V8 computes `Math.sin` and `Math.cos` with
// fdlibm, Chromium 147's are correctly rounded but for near-ties, and
// `Math.pow` comes from different libraries (docs/phase2-plan.md, P2-6a).
// This script serves tools/three-oracle on 127.0.0.1 for the page
// (oracle.html), which runs run.mjs and returns the results.

import { createServer } from 'node:http';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, normalize, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { launch } from '../board-reference/chromium.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
const fixtures = join(root, 'samples', 'three', 'tests', 'fixtures');
const [chromePath] = process.argv.slice(2);
if (!chromePath) {
  console.error('usage: node tools/three-oracle/oracle.mjs CHROME');
  process.exit(2);
}
const version = JSON.parse(readFileSync(join(here, 'node_modules', 'three', 'package.json'), 'utf8')).version;

const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.mjs': 'text/javascript', '.json': 'application/json' };
const server = createServer((request, response) => {
  const path = decodeURIComponent(new URL(request.url, 'http://127.0.0.1').pathname);
  const file = path === '/cases.json' ? join(fixtures, 'cases.json') : normalize(join(here, path));
  if (!(file === join(fixtures, 'cases.json') || file.startsWith(here + sep))) {
    response.writeHead(403).end();
    return;
  }
  try {
    const body = readFileSync(file);
    response.writeHead(200, { 'content-type': TYPES[extname(file)] ?? 'application/octet-stream' }).end(body);
  } catch {
    response.writeHead(404).end();
  }
});
await new Promise((done) => server.listen(0, '127.0.0.1', done));
const { port } = server.address();

const browser = await launch(chromePath, { width: 800, height: 600 });
let groups;
try {
  await browser.cdp.load(`http://127.0.0.1:${port}/oracle.html`);
  for (let attempt = 0; attempt < 200; attempt++) {
    if (await browser.cdp.evaluate('typeof window.runOracle === "function"')) break;
    await new Promise((done) => setTimeout(done, 50));
  }
  groups = JSON.parse(await browser.cdp.evaluate('window.runOracle()'));
} finally {
  await browser.close();
  server.close();
}

// One result per line keeps the fixture reviewable.
const lines = groups.map(
  (g) => `  {"name": ${JSON.stringify(g.name)}, "results": [\n${g.results.map((r) => `    ${JSON.stringify(r)}`).join(',\n')}\n  ]}`,
);
writeFileSync(
  join(fixtures, `three-${version}.json`),
  [
    '{',
    `"comment": "Generated by tools/three-oracle/oracle.mjs from cases.json; do not edit.",`,
    `"three": ${JSON.stringify(version)},`,
    `"chromium": ${JSON.stringify(browser.version)},`,
    '"groups": [',
    lines.join(',\n'),
    ']',
    '}',
    '',
  ].join('\n'),
);
console.log(`three ${version} in ${browser.version}, ${groups.reduce((n, g) => n + g.results.length, 0)} results`);
