"""Writes samples/three-render/tests/fixtures/scene.json: the three.js
shell's scene (P2-6c) and the views to render it from.

The scene is the shell's objects (tools/three-reference/shell.js, OBJECTS)
as meshes, on a floor. The views are the distinct camera states and canvas
sizes the shell's Chromium reference recorded
(samples/three-shell/tests/fixtures/fidelity/shell-chromium.json): each one
the first snapshot with that state.

    python -I tools/three-render-reference/make_scene.py
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SHELL = ROOT / "samples/three-shell/tests/fixtures/fidelity/shell-chromium.json"
OUT = ROOT / "samples/three-render/tests/fixtures/scene.json"

# The shell's camera: new PerspectiveCamera(50, aspect, 0.1, 100).
FOV, NEAR, FAR = 50, 0.1, 100

OBJECTS = [
    {"name": "floor", "geometry": {"type": "box", "args": [8, 0.1, 8, 1, 1, 1]}, "color": 0x55606B,
     "position": [0, -0.05, 0], "rotation": [0, 0, 0]},
    {"name": "origin", "geometry": {"type": "sphere", "args": [0.15, 12, 8]}, "color": 0xF0F0F0,
     "position": [0, 0, 0], "rotation": [0, 0, 0]},
    {"name": "box", "geometry": {"type": "box", "args": [1, 1, 1, 1, 1, 1]}, "color": 0xD04A3A,
     "position": [2, 0.5, -1], "rotation": [0, 0.5, 0]},
    {"name": "sphere", "geometry": {"type": "sphere", "args": [0.75, 32, 16]}, "color": 0x3A7FD0,
     "position": [-1.5, 1, 1.5], "rotation": [0, 0, 0]},
]


def main():
    shell = json.loads(SHELL.read_text(encoding="utf-8"))
    views, seen = [], set()
    for scenario, snapshots in shell["scenarios"].items():
        for i, snapshot in enumerate(snapshots):
            canvas = next(e for e in snapshot["elements"] if e["name"] == "view")
            width = int(canvas["attributes"]["width"])
            height = int(canvas["attributes"]["height"])
            camera = snapshot["camera"]
            state = {
                "position": camera["position"],
                "quaternion": camera["quaternion"],
                "aspect": camera["aspect"],
                "zoom": camera["zoom"],
            }
            key = json.dumps([width, height, state])
            if key in seen:
                continue
            seen.add(key)
            views.append({"name": f"{scenario}-{i}", "width": width, "height": height, "camera": state})
    scene = {
        "comment": "Generated by tools/three-render-reference/make_scene.py; do not edit.",
        "background": 0x202830,
        "camera": {"fov": FOV, "near": NEAR, "far": FAR},
        "objects": OBJECTS,
        "views": views,
    }
    # One object and one view per line keeps the fixture reviewable.
    head = ",\n".join(f" {json.dumps(k)}: {json.dumps(scene[k])}" for k in ("comment", "background", "camera"))
    objects = ",\n".join(f"  {json.dumps(o)}" for o in OBJECTS)
    lines = ",\n".join(f"  {json.dumps(v)}" for v in views)
    text = "{\n" + head + ',\n "objects": [\n' + objects + '\n ],\n "views": [\n' + lines + "\n ]\n}\n"
    json.loads(text)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(views)} views")


if __name__ == "__main__":
    main()
