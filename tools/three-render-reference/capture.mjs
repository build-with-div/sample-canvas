// Records what samples/three-render's test compares the port with: the
// scene in samples/three-render/tests/fixtures/scene.json, rendered by
// three.js 0.187.0's WebGPURenderer on SwiftShader WebGPU in pinned
// Chromium (docs/webgpu-oracle.md).
//
//     python -I tools/three-render-reference/make_scene.py
//     npm ci --prefix tools/three-oracle
//     node tools/three-render-reference/capture.mjs CHROME
//
// CHROME is the `chrome` binary of Chrome for Testing 147.0.7727.50. Writes
// tests/fixtures/scene-chromium.json (the geometry hashes and the adapter)
// and one PNG per view in tests/fixtures/scene-chromium/.

import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { deflateSync } from 'node:zlib';
import { launch } from '../board-reference/chromium.mjs';
import { swiftshaderFlags } from '../webgpu-oracle/flags.mjs';
import { ready, serve } from '../webgpu-oracle/serve.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const fixtures = join(root, 'samples', 'three-render', 'tests', 'fixtures');
const [chromePath] = process.argv.slice(2);
if (!chromePath) {
  console.error('usage: node tools/three-render-reference/capture.mjs CHROME');
  process.exit(2);
}
const spec = JSON.parse(readFileSync(join(fixtures, 'scene.json'), 'utf8'));
const three = JSON.parse(readFileSync(join(root, 'tools', 'three-oracle', 'node_modules', 'three', 'package.json'), 'utf8')).version;

// An 8-bit RGBA PNG, unfiltered rows.
const CRC = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(bytes) {
  let c = 0xffffffff;
  for (const b of bytes) c = CRC[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const out = Buffer.alloc(12 + data.length);
  out.writeUInt32BE(data.length, 0);
  out.write(type, 4, 'ascii');
  data.copy(out, 8);
  out.writeUInt32BE(crc32(out.subarray(4, 8 + data.length)), 8 + data.length);
  return out;
}
function png(width, height, rgba) {
  const header = Buffer.alloc(13);
  header.writeUInt32BE(width, 0);
  header.writeUInt32BE(height, 4);
  header.set([8, 6, 0, 0, 0], 8);
  const rows = Buffer.alloc((width * 4 + 1) * height);
  for (let y = 0; y < height; y++) rgba.copy(rows, y * (width * 4 + 1) + 1, y * width * 4, (y + 1) * width * 4);
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', header),
    chunk('IDAT', deflateSync(rows, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

const server = await serve();
const browser = await launch(chromePath, { width: 400, height: 300, gpu: swiftshaderFlags() });
let result;
try {
  await browser.cdp.load(server.url('three-render-reference/scene.html'));
  await ready(browser.cdp, 'renderScene');
  result = await browser.cdp.evaluate(`renderScene(${JSON.stringify(spec)})`);
} finally {
  await browser.close();
  await server.close();
}
if (!result.adapter.isFallbackAdapter || result.adapter.architecture !== 'swiftshader') {
  throw new Error(`rendered on ${JSON.stringify(result.adapter)}, not SwiftShader`);
}

const dir = join(fixtures, 'scene-chromium');
mkdirSync(dir, { recursive: true });
for (const file of readdirSync(dir)) rmSync(join(dir, file));
for (const view of spec.views) {
  const rgba = Buffer.from(result.views[view.name], 'base64');
  writeFileSync(join(dir, `${view.name}.png`), png(view.width, view.height, rgba));
}
const lines = Object.entries(result.geometry).map(([name, g]) => `  ${JSON.stringify(name)}: ${JSON.stringify(g)}`);
writeFileSync(
  join(fixtures, 'scene-chromium.json'),
  [
    '{',
    '"comment": "Generated by tools/three-render-reference/capture.mjs from scene.json; do not edit. Views are PNGs in scene-chromium/.",',
    `"three": ${JSON.stringify(three)},`,
    `"chromium": ${JSON.stringify(browser.version)},`,
    `"adapter": ${JSON.stringify(result.adapter)},`,
    '"geometry": {',
    lines.join(',\n'),
    '}',
    '}',
    '',
  ].join('\n'),
);
console.log(`${spec.views.length} views, ${Object.keys(result.geometry).length} geometries, ${browser.version}`);
