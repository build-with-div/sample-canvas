// Replays samples/board/tests/fixtures/fidelity/board-scenarios.json on the
// board reference page (board.html) in pinned Chromium, over the DevTools
// protocol, and writes what the page shows after each step.
//
//     cd tools/rough-oracle && npm ci && cd ../..
//     node tools/board-reference/capture.mjs CHROME samples/board/tests/fixtures/fidelity/board-chromium.json
//
// CHROME is the `chrome` binary of Chrome for Testing 147.0.7727.50, the
// build Div's census pins. samples/board/tests/fidelity_board.rs replays
// the same steps on Div and compares.
//
// Input arrives as trusted browser input (Input.dispatchMouseEvent and
// Input.dispatchKeyEvent), so Chromium produces the pointer, mouse, click
// and key events itself. The page settles after each step (two frames and
// a task), so its requestAnimationFrame redraw has run.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { launch } from './chromium.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
const [chromePath, outputPath] = process.argv.slice(2);
if (!chromePath || !outputPath) {
  console.error('usage: node tools/board-reference/capture.mjs CHROME OUTPUT');
  process.exit(2);
}
const spec = JSON.parse(readFileSync(join(root, 'samples/board/tests/fixtures/fidelity/board-scenarios.json'), 'utf8'));
const page = pathToFileURL(join(here, 'board.html')).href;
const roughjs = JSON.parse(readFileSync(join(root, 'tools/rough-oracle/node_modules/roughjs/package.json'), 'utf8')).version;

// key: [code, Windows virtual-key code]
const KEYS = {
  r: ['KeyR', 82],
  o: ['KeyO', 79],
  l: ['KeyL', 76],
  2: ['Digit2', 50],
  4: ['Digit4', 52],
  Escape: ['Escape', 27],
  Delete: ['Delete', 46],
  Backspace: ['Backspace', 8],
};

async function mouse(cdp, kind, x, y, pressed) {
  const type = { move: 'mouseMoved', down: 'mousePressed', up: 'mouseReleased' }[kind];
  if (kind === 'down') pressed.left = true;
  if (kind === 'up') pressed.left = false;
  await cdp.send('Input.dispatchMouseEvent', {
    type,
    x,
    y,
    button: kind === 'move' && !pressed.left ? 'none' : 'left',
    buttons: pressed.left ? 1 : 0,
    clickCount: kind === 'move' ? 0 : 1,
    pointerType: 'mouse',
  });
}

async function step(cdp, entry, pressed) {
  if (entry.mouse) {
    await mouse(cdp, entry.mouse, entry.x, entry.y, pressed);
  } else if (entry.click) {
    const [x, y] = entry.click;
    for (const kind of ['move', 'down', 'up']) await mouse(cdp, kind, x, y, pressed);
  } else if (entry.key) {
    const [code, vk] = KEYS[entry.key] ?? [];
    if (!code) throw new Error(`unknown key ${entry.key}`);
    const key = { key: entry.key, code, windowsVirtualKeyCode: vk, nativeVirtualKeyCode: vk };
    await cdp.send('Input.dispatchKeyEvent', { type: 'rawKeyDown', ...key });
    await cdp.send('Input.dispatchKeyEvent', { type: 'keyUp', ...key });
  } else {
    throw new Error(`unknown step ${JSON.stringify(entry)}`);
  }
}

const browser = await launch(chromePath, spec.host);
const scenarios = {};
try {
  const { cdp } = browser;
  for (const scenario of spec.scenarios) {
    await cdp.load(`${page}?${scenario.id}`);
    await cdp.evaluate('window.__board.settle()');
    const snapshots = [await cdp.evaluate('window.__board.snapshot()')];
    const pressed = { left: false };
    for (const entry of scenario.steps) {
      await step(cdp, entry, pressed);
      await cdp.evaluate('window.__board.settle()');
      snapshots.push(await cdp.evaluate('window.__board.snapshot()'));
    }
    scenarios[scenario.id] = snapshots;
    console.log(`${scenario.id}: ${snapshots.length} snapshots`);
  }
} finally {
  await browser.close();
}

// One snapshot per line keeps the fixture reviewable.
const comment =
  'Generated by tools/board-reference/capture.mjs from board-scenarios.json; do not edit. ' +
  'Snapshot 0 is after load, snapshot n after step n.';
const lines = Object.entries(scenarios).map(
  ([id, snapshots]) => `    ${JSON.stringify(id)}: [\n${snapshots.map((s) => `      ${JSON.stringify(s)}`).join(',\n')}\n    ]`,
);
writeFileSync(
  outputPath,
  [
    '{',
    `  "comment": ${JSON.stringify(comment)},`,
    `  "chromium": ${JSON.stringify(browser.version)},`,
    `  "roughjs": ${JSON.stringify(roughjs)},`,
    '  "scenarios": {',
    lines.join(',\n'),
    '  }',
    '}',
    '',
  ].join('\n'),
);
console.log(browser.version);
